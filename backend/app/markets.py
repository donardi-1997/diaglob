MARKETS_BY_CODE = {
    market["country_code"]:
        market
    for market in AMERICA_MARKETS
}


def get_market(
    country_code: str,
):
    return MARKETS_BY_CODE.get(
        country_code
        .strip()
        .upper()
    )


def get_market_defaults(
    country_code: str,
):
    market = get_market(
        country_code
    )

    if not market:
        return None

    return {
        "country_code":
            market["country_code"],

        "currency":
            market["currency"],

        "timezone":
            market["default_timezone"],

        "default_language":
            market["default_language"],
    }
